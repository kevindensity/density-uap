#!/usr/bin/env python3
"""Generate the Conformance traceability table from matrix.yaml and check it against the code.

Fails (exit 1) if a referenced test does not exist in the workspace or the TLA+ model,
or if a core law enforced in B0 has no test. Prints the markdown table on success.
"""
import pathlib, re, sys, yaml

root = pathlib.Path(__file__).resolve().parent.parent
m = yaml.safe_load((root / "traceability/matrix.yaml").read_text())
rust = "\n".join(p.read_text() for p in root.glob("crates/**/*.rs"))
tla = (root / "tla/Kernel.tla").read_text()

def exists(ref: str) -> bool:
    kind, _, name = ref.partition("::")
    name = name.split(" ")[0]
    if kind == "tla":
        return re.search(rf"^{re.escape(name)} ==", tla, re.M) is not None
    return re.search(rf"\b(fn|struct) {re.escape(name)}\b", rust) is not None

errors = []
for law in m["laws"]:
    for t in law["tests"]:
        if not exists(t):
            errors.append(f"{law['id']}: test not found: {t}")
    if law["tier"] == "core" and law["phase"].startswith("B0") and not law["tests"]:
        law["status"] = "specified (B0 test due)"
    else:
        law["status"] = "oracle-tested" if law["tests"] else "specified"
if errors:
    print("\n".join(errors), file=sys.stderr)
    sys.exit(1)

core = [l for l in m["laws"] if l["tier"] == "core"]
ext = [l for l in m["laws"] if l["tier"] == "extension"]
print(f"<!-- generated by traceability/generate.py from matrix.yaml {m['version']}: {len(core)} core, {len(ext)} extension -->")
print("| Law | Tier | Phase | Machines | Contracts | Status | Tests |")
print("| --- | --- | --- | --- | --- | --- | --- |")
for l in core + ext:
    tests = "; ".join(f"`{t}`" for t in l["tests"]) or "—"
    print(f"| {l['id']} {l['law']} | {l['tier']} | {l['phase']} | {l['machines']} | {l['contracts']} | {l['status']} | {tests} |")
