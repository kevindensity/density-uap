#!/usr/bin/env python3
"""Generate Rust, TypeScript and SQL from contracts/schemas/*.json (JSON Schema 2020-12 with x-density annotations).

One source, three targets. The generated files must never be edited by hand: CI and the drift gate regenerate them
and fail on any difference. Usage: contracts/gen.py [--check]
"""
import glob, hashlib, json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUST = os.path.join(ROOT, 'services/crates/dc-contracts/src/lib.rs')
TS = os.path.join(ROOT, 'packages/contracts/src/index.ts')
SQL = os.path.join(ROOT, 'contracts/generated/schemas.sql')

def canon(x): return json.dumps(x, sort_keys=True, separators=(',', ':'), ensure_ascii=False)
def digest(x): return hashlib.sha256(canon(x).encode()).hexdigest()
def pascal(s): return ''.join(p[:1].upper() + p[1:] for p in re.split(r'[^A-Za-z0-9]+', s) if p)

class Gen:
    def __init__(self): self.rs, self.ts = [], []
    def types(self, s):
        t = s.get('type'); return t if isinstance(t, list) else ([t] if t else [])
    def rust(self, s, name):
        if 'enum' in s:
            n = name; v = [(pascal(e) or 'Empty', e) for e in s['enum']]
            self.rs.append('#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]\npub enum %s {\n%s}\n' % (n, ''.join('    #[serde(rename = %s)]\n    %s,\n' % (json.dumps(e), i) for i, e in v)))
            self.ts.append('export type %s = %s;\n' % (n, ' | '.join(json.dumps(e) for _, e in v)))
            return n, n
        ts = self.types(s); nullable = 'null' in ts; base = [x for x in ts if x != 'null']
        if not base: r, t = 'serde_json::Value', 'unknown'
        else:
            b = base[0]
            if b == 'string': r, t = 'String', 'string'
            elif b == 'integer': r, t = 'i64', 'number'
            elif b == 'number': r, t = 'f64', 'number'
            elif b == 'boolean': r, t = 'bool', 'boolean'
            elif b == 'array':
                ir, it = self.rust(s.get('items', {}), name + 'Item'); r, t = 'Vec<%s>' % ir, '%s[]' % it
            elif b == 'object' and 'properties' in s:
                n = s.get('x-density', {}).get('name', name); self.struct(s, n); r, t = n, n
            elif b == 'object' and isinstance(s.get('additionalProperties'), dict):
                ir, it = self.rust(s['additionalProperties'], name + 'Value'); r, t = 'std::collections::BTreeMap<String, %s>' % ir, 'Record<string, %s>' % it
            else: r, t = 'serde_json::Map<String, serde_json::Value>', 'Record<string, unknown>'
        return ('Option<%s>' % r, t + ' | null') if nullable else (r, t)
    def struct(self, s, name):
        fields_rs, fields_ts = [], []
        req = set(s.get('required', []))
        for f, fs in s.get('properties', {}).items():
            r, t = self.rust(fs, name + pascal(f))
            ident = f if f not in ('type', 'ref', 'match') else f + '_'
            attrs = '' if ident == f else '    #[serde(rename = %s)]\n' % json.dumps(f)
            if f not in req:
                attrs += '    #[serde(default, skip_serializing_if = "Option::is_none")]\n'
                if not r.startswith('Option<'): r = 'Option<%s>' % r
            fields_rs.append('%s    pub %s: %s,\n' % (attrs, ident, r))
            fields_ts.append('  %s%s: %s;\n' % (f, '' if f in req else '?', t))
        deny = '#[serde(deny_unknown_fields)]\n' if s.get('additionalProperties') is False else ''
        doc = ('/// %s\n' % s['description']) if s.get('description') else ''
        self.rs.append('%s#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n%spub struct %s {\n%s}\n' % (doc, deny, name, ''.join(fields_rs)))
        self.ts.append('export interface %s {\n%s}\n' % (name, ''.join(fields_ts)))

def build():
    schemas = [(f, json.load(open(f))) for f in sorted(glob.glob(os.path.join(ROOT, 'contracts/schemas/*.json')))]
    g = Gen(); consts_rs, consts_ts, sql = [], [], []
    for f, s in schemas:
        name = s['title']; g.struct(s, name); d = digest(s); sid = s['$id']
        consts_rs.append('    (%s, %s, %s),\n' % (json.dumps(sid), json.dumps(d), json.dumps(name)))
        consts_ts.append('  %s: %s,\n' % (json.dumps(sid), json.dumps(d)))
        sql.append("(%s, '%s', $s$%s$s$::jsonb)" % ("'" + sid.replace("'", "''") + "'", d, canon(s)))
    hdr = 'GENERATED by contracts/gen.py from contracts/schemas. Do not edit by hand.'
    rust = '// %s\n#![allow(clippy::all)]\nuse serde::{Deserialize, Serialize};\n\n/// (schema id, SHA-256 of the canonical schema, Rust type)\npub const SCHEMAS: &[(&str, &str, &str)] = &[\n%s];\n\n%s' % (hdr, ''.join(consts_rs), '\n'.join(g.rs))
    ts = '// %s\nexport const SCHEMA_DIGESTS = {\n%s} as const;\n\n%s' % (hdr, ''.join(consts_ts), '\n'.join(g.ts))
    sq = '-- %s\ninsert into contracts.schemas (schema_id, sha256, schema) values\n%s\non conflict (schema_id, sha256) do nothing;\n' % (hdr, ',\n'.join(sql))
    return {RUST: rust, TS: ts, SQL: sq}

if __name__ == '__main__':
    out = build(); stale = []
    for path, text in out.items():
        if '--check' in sys.argv:
            if not os.path.exists(path) or open(path).read() != text: stale.append(os.path.relpath(path, ROOT))
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True); open(path, 'w').write(text)
    if stale: print('STALE generated files:', ', '.join(stale)); sys.exit(1)
    print('ok' if '--check' in sys.argv else 'generated %d files' % len(out))
